/*
 * Generates the types of the package from the runtime props of the components:
 * types/aloha-vue.d.ts (TypeScript, Volar) and web-types.json (JetBrains IDEs).
 * Other exports (functions, plugins, constants) are typed as any.
 *
 * Run: npm run build-types
 */
import fs from "node:fs";
import path from "node:path";
import {
  createServer,
} from "vite";

const ROOT = path.resolve(import.meta.dirname, "..");
const PACKAGE = JSON.parse(fs.readFileSync(path.join(ROOT, "package.json"), "utf8"));
const DOCS_URL = "https://ilia-brykin.github.io/aloha/";

// Some modules use the DOM on import
const { JSDOM } = await import("jsdom");
const DOM = new JSDOM("");
globalThis.window ??= DOM.window;
globalThis.document ??= DOM.window.document;
globalThis.navigator ??= DOM.window.navigator;
globalThis.DOMParser ??= DOM.window.DOMParser;
globalThis.Node ??= DOM.window.Node;

const server = await createServer({
  configFile: false,
  root: ROOT,
  logLevel: "error",
  server: { middlewareMode: true, hmr: false },
  appType: "custom",
});
const ALOHA = await server.ssrLoadModule(path.join(ROOT, "src/index.js"));
await server.close();

const TS_TYPES = new Map([
  [String, "string"],
  [Number, "number"],
  [Boolean, "boolean"],
  [Array, "any[]"],
  [Object, "Record<string, any>"],
  [Function, "((...args: any[]) => any)"],
  [Date, "Date"],
  [Symbol, "symbol"],
  [Promise, "Promise<any>"],
]);

const isComponent = value => !!value
  && typeof value === "object"
  && (typeof value.render === "function" || typeof value.setup === "function");

function normalizeProps(props = {}) {
  if (Array.isArray(props)) {
    return props.map(name => ({ name, types: [], required: false }));
  }
  return Object.entries(props).map(([name, option]) => {
    const TYPE = option && typeof option === "object" && !Array.isArray(option) ? option.type : option;
    const TYPES = (Array.isArray(TYPE) ? TYPE : [TYPE]).filter(type => type !== undefined && type !== null);
    let defaultValue;
    if (option && typeof option === "object" && "default" in option) {
      const DEFAULT = option.default;
      if (typeof DEFAULT !== "function" || TYPES.includes(Function)) {
        defaultValue = typeof DEFAULT === "function" ? undefined : DEFAULT;
      } else {
        try {
          defaultValue = DEFAULT();
        } catch {
          defaultValue = undefined;
        }
      }
    }
    return {
      name,
      types: TYPES,
      required: !!option?.required,
      default: defaultValue,
    };
  });
}

const tsType = types => {
  const NAMES = [...new Set(types.map(type => TS_TYPES.get(type) ?? "any"))];
  return NAMES.length && !NAMES.includes("any") ? NAMES.join(" | ") : "any";
};

const jsonDefault = value => {
  if (value === undefined) {
    return undefined;
  }
  try {
    return JSON.stringify(value);
  } catch {
    return undefined;
  }
};

const COMPONENTS = [];
const OTHERS = [];
for (const [exportName, value] of Object.entries(ALOHA).sort(([a], [b]) => a.localeCompare(b))) {
  if (isComponent(value)) {
    COMPONENTS.push({
      exportName,
      props: normalizeProps(value.props),
      emits: Array.isArray(value.emits) ? value.emits : Object.keys(value.emits || {}),
    });
  } else {
    OTHERS.push(exportName);
  }
}

// ---------- types/aloha-vue.d.ts ----------

const D_TS = [
  "// Generated by `npm run build-types` (scripts/build-types.mjs). Do not edit by hand.",
  "// Docs of every component: node_modules/aloha-vue/AGENTS.md",
  "import type { ComponentOptionsMixin, DefineComponent } from \"vue\";",
  "",
];
for (const component of COMPONENTS) {
  D_TS.push(`export interface ${ component.exportName }Props {`);
  for (const prop of component.props) {
    const DEFAULT = jsonDefault(prop.default);
    if (DEFAULT !== undefined) {
      D_TS.push(`  /** @default ${ DEFAULT.replace(/\*\//g, "*\\/") } */`);
    }
    D_TS.push(`  ${ /^[A-Za-z_$][\w$]*$/.test(prop.name) ? prop.name : JSON.stringify(prop.name) }${ prop.required ? "" : "?" }: ${ tsType(prop.types) };`);
  }
  D_TS.push("}");
  const EMITS = component.emits.length ? component.emits.map(emit => JSON.stringify(emit)).join(" | ") : "never";
  D_TS.push(`export declare const ${ component.exportName }: DefineComponent<${ component.exportName }Props, {}, {}, {}, {}, ComponentOptionsMixin, ComponentOptionsMixin, (${ EMITS })[]>;`, "");
}
D_TS.push("// shortcut: functions, plugins and constants are not typed yet, upgrade when JSDoc types exist in src/");
for (const name of OTHERS) {
  D_TS.push(`export declare const ${ name }: any;`);
}
D_TS.push(
  "",
  "declare module \"vue\" {",
  "  export interface GlobalComponents {",
  ...COMPONENTS.map(component => `    ${ component.exportName }: typeof ${ component.exportName };`),
  "  }",
  "}",
  "",
);
fs.mkdirSync(path.join(ROOT, "types"), { recursive: true });
fs.writeFileSync(path.join(ROOT, "types/aloha-vue.d.ts"), D_TS.join("\n"));

// ---------- web-types.json ----------

const WEB_TYPES = {
  $schema: "https://raw.githubusercontent.com/JetBrains/web-types/master/schema/web-types.json",
  framework: "vue",
  name: PACKAGE.name,
  version: PACKAGE.version,
  "js-types-syntax": "typescript",
  "description-markup": "markdown",
  contributions: {
    html: {
      "vue-components": COMPONENTS.map(component => ({
        name: component.exportName,
        source: { module: PACKAGE.name, symbol: component.exportName },
        "doc-url": DOCS_URL,
        props: component.props.map(prop => ({
          name: prop.name,
          type: tsType(prop.types),
          required: prop.required || undefined,
          default: jsonDefault(prop.default),
        })),
        js: {
          events: component.emits.map(name => ({ name })),
        },
      })),
    },
  },
};
fs.writeFileSync(path.join(ROOT, "web-types.json"), `${ JSON.stringify(WEB_TYPES, null, 2) }\n`);

// Self-check: the components are found and their props are read
const BUTTON = COMPONENTS.find(component => component.exportName === "AButton");
if (COMPONENTS.length < 80 || !BUTTON?.props.some(prop => prop.name === "text" && prop.types.length)) {
  throw new Error(`components are not read correctly: ${ COMPONENTS.length }`);
}
console.log(`types: ${ COMPONENTS.length } components, ${ OTHERS.length } other exports`);
